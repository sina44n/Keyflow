"""
Accounts Signals — Auto-create Profile and Preferences, secure password reset delivery,
and Knox session invalidation upon password reset.
"""
import logging
from django.db.models.signals import post_save
from django.dispatch import receiver
from django.core.mail import EmailMultiAlternatives
from django.conf import settings
from rest_framework import status
from rest_framework.exceptions import APIException
from knox.models import AuthToken
from django_rest_passwordreset.signals import (
    reset_password_token_created,
    post_password_reset,
)

from .models import User, UserProfile, UserPreferences

logger = logging.getLogger(__name__)


class EmailDeliveryUnavailable(APIException):
    status_code = status.HTTP_503_SERVICE_UNAVAILABLE
    default_detail = "Unable to dispatch password reset email. Please try again later or contact support."
    default_code = "email_delivery_failed"


@receiver(post_save, sender=User)
def create_user_profile_and_preferences(sender, instance, created, **kwargs):
    """Automatically create UserProfile and UserPreferences on User creation."""
    if created:
        UserProfile.objects.get_or_create(user=instance)
        UserPreferences.objects.get_or_create(user=instance)


@receiver(post_save, sender=User)
def save_user_profile(sender, instance, **kwargs):
    """Save profile when user is saved."""
    if hasattr(instance, 'profile'):
        instance.profile.save()


