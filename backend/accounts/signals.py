"""
Accounts Signals — Auto-create Profile and Preferences on new User creation.
"""
from django.db.models.signals import post_save
from django.dispatch import receiver
from django.core.mail import send_mail
from django.conf import settings
from django_rest_passwordreset.signals import reset_password_token_created

from .models import User, UserProfile, UserPreferences


@receiver(post_save, sender=User)
def create_user_profile_and_preferences(sender, instance, created, **kwargs):
    """Automatically create UserProfile and UserPreferences on User creation."""
    if created:
        UserProfile.objects.get_or_create(user=instance)
        UserPreferences.objects.get_or_create(user=instance)


@receiver(post_save, sender=User)
def save_user_profile(sender, instance, **kwargs):
    """Save profile when user is saved."""
    if hasattr(instance, 'profile'):
        instance.profile.save()


@receiver(reset_password_token_created)
def password_reset_token_created(sender, instance, reset_password_token, *args, **kwargs):
    """
    Handles password reset tokens generated by django_rest_passwordreset.
    Constructs password reset link and dispatches via configured email backend.
    """
    frontend_url = getattr(settings, 'FRONTEND_URL', 'http://localhost:5173').rstrip('/')
    reset_url = f"{frontend_url}/reset-password?token={reset_password_token.key}"

    email_text = (
        f"Hello {reset_password_token.user.username},\n\n"
        f"You requested to reset your password for KEYFLOW.\n\n"
        f"Click the link below to set a new password:\n"
        f"{reset_url}\n\n"
        f"Your single-use reset token:\n"
        f"{reset_password_token.key}\n\n"
        f"This token is valid for 24 hours. If you did not request this, please ignore this email.\n\n"
        f"Happy typing,\nThe KEYFLOW Team"
    )

    send_mail(
        subject="KEYFLOW — Password Reset Request",
        message=email_text,
        from_email=getattr(settings, 'DEFAULT_FROM_EMAIL', 'KEYFLOW <no-reply@keyflow.app>'),
        recipient_list=[reset_password_token.user.email],
        fail_silently=False,
    )
