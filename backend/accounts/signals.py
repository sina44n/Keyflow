@receiver(post_password_reset)
def on_post_password_reset(sender, user, *args, **kwargs):
    """
    Invalidate all active Knox auth tokens for this user when password is changed/reset.
    Forces all devices to log in again with new password.
    """
    AuthToken.objects.filter(user=user).delete()

